/// `CTyre::CSetup`'s vtable (0x72e624) and `CTyre::CTyreTypes`' (0x72e674).
const SETUP_VTABLE: u32 = 0x0072_E624;
const TYRE_TYPE_VTABLE: u32 = 0x0072_E674;
/// The setup's word after its reals: the tyre type `CopyDefFrom` copies from.
const SETUP_TYPE: u32 = 0x2C;

/// `CTyre::CSetup::CSetup` (0x47bd60) on the setup at `this`: an unnamed tweak, its vtable, the unsigned at +0xc and
/// the real at +0x1c (`Pressure`). The tyre type word (+0x2c) is not the constructor's.
pub fn construct_setup(mem: &mut Mem, this: u32) {
    ntweak::construct_base(mem, this, 0);
    mem.set_u32(this, SETUP_VTABLE);
    ntweak::construct_unsigned(mem, this + 0xC);
    ntweak::construct_real(mem, this + 0x1C);
}

/// `CTyre::CSetupOptions`'s vtable (0x72e8b4).
const OPTIONS_VTABLE: u32 = 0x0072_E8B4;

/// `CTyre::CSetupOptions::CSetupOptions` (0x47da30) on the options at `this`: an unnamed tweak, its vtable, and the
/// `Pressure` range (`E13RealTriple`: `Min`, `Max`, `Step`) from +0xc.
pub fn construct_options(mem: &mut Mem, this: u32) {
    ntweak::construct_base(mem, this, 0);
    mem.set_u32(this, OPTIONS_VTABLE);
    for at in (0xC..0x3C).step_by(0x10) {
        ntweak::construct_real(mem, this + at);
    }
}

/// The tyre type of the setup at `this`, as the setup's emit (0x48e620) stores it before the car copies the setup.
pub fn set_setup_type(mem: &mut Mem, this: u32, tyre_type: u32) {
    mem.set_u32(this + SETUP_TYPE, tyre_type);
}

/// `CTyre::CTyreTypes::CTyreTypes` (0x47c040) on the tyre type at `this`: an unnamed tweak, its vtable, the unsigned at
/// +0xc (`Type`), then reals from +0x1c to +0x69c, 0x10 apart (single ones and arrays, all zero).
pub fn construct_tyre_type(mem: &mut Mem, this: u32) {
    ntweak::construct_base(mem, this, 0);
    mem.set_u32(this, TYRE_TYPE_VTABLE);
    ntweak::construct_unsigned(mem, this + 0xC);
    for at in (0x1C..=0x69C).step_by(0x10) {
        ntweak::construct_real(mem, this + at);
    }
}

/// `CTyre::CState::CState(a, b, c)` (0x531500, thiscall, `ret 0xC`) on the state at `this`: writes the defaults.
pub fn construct_state(mem: &mut Mem, this: u32) {
    for (at, bits) in CSTATE_DEFAULTS {
        mem.set_u32(this + at, bits);
    }
}
