#!/usr/bin/env python3
"""Regenerate rust/rbr-physics/src/ngp/exe_patches.rs: NGP 7.4.778's edits to the 1.02 executable's `.text` and
`.rdata`, as a snapshot of an NGP run holds them, for the boot to apply (`rbr-standalone --boot --ngp-physics`).

The patches are the byte runs where the snapshot's exe image differs from the exe file, less the harness's own hooks
(`HARNESS`: its trampolines, the recorder's hook of the car's control input, a vtable slot) and the import table the
loader fills. Runs closer than 5 bytes are merged. NGP's calls, jumps and pointers into itself hold addresses at the
snapshot's base of NGP.dll, which the boot uses too (`BASE`).

Run from the repo root with the harness venv:

    .venv/bin/python -I -B scripts/gen-ngp-exe-patches.py SNAPSHOT [--write]

SNAPSHOT is an NGP run's snapshot (`ngp-load11c.snap-40.bin`); the exe is `$RBR_PATCH/RichardBurnsRally_SSE.exe`. Without
`--write` the script checks that its output matches the checked-in file byte for byte and exits nonzero when it does
not. The output goes through `rustfmt`.
"""

import argparse
import os
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.append(os.path.join(ROOT, "harness"))
import replay  # noqa: E402

OUT = os.path.join(ROOT, "rust", "rbr-physics", "src", "ngp", "exe_patches.rs")
BASE = 0x791A0000
# The harness's edits: its trampolines (0x4804f0, 0x48cd90), the recorder's hook of `CCar::UpdateSeed` (0x4e91f0), the
# import table (0x729000..) and the plugin's vtable slot (0x73f994).
HARNESS = [(0x4804F0, 0x4804F7), (0x48CD90, 0x48CD96), (0x4E91F0, 0x4E91F6), (0x729000, 0x729800), (0x73F994, 0x73F998)]


def sections(exe):
    pe, = struct.unpack_from("<I", exe, 0x3C)
    count, = struct.unpack_from("<H", exe, pe + 6)
    optional, = struct.unpack_from("<H", exe, pe + 20)
    for i in range(count):
        at = pe + 24 + optional + 40 * i
        name = exe[at:at + 8].rstrip(b"\0").decode()
        vsize, va, rsize, raw = struct.unpack_from("<IIII", exe, at + 8)
        yield name, 0x400000 + va, exe[raw:raw + min(vsize, rsize)]


def patches(snap, exe):
    out = []
    for name, base, data in sections(exe):
        if name not in (".text", ".rdata"):
            continue
        have = snap.read(base, len(data))
        runs = []
        for k in range(len(data)):
            if have[k] != data[k]:
                if runs and k - runs[-1][1] <= 4:
                    runs[-1][1] = k + 1
                else:
                    runs.append([k, k + 1])
        for lo, hi in runs:
            at = base + lo
            if any(a < base + hi and at < b for a, b in HARNESS):
                continue
            out.append((at, have[lo:hi]))
    return out


def render(found):
    lines = [
        "//! NGP 7.4.778's edits to the 1.02 executable's `.text` and `.rdata` (generated by",
        "//! `scripts/gen-ngp-exe-patches.py` from an NGP run's snapshot; do not edit): NGP's retargeted calls and jumps, its",
        "//! repointed constants and vtable slots, NOPs and immediates. Addresses into NGP.dll are at its base",
        "//! [`BASE`]. The per-car immediates (0x4f13a7, 0x53daa6) are the snapshot car's; `car_init` rewrites them.",
        "",
        "/// NGP.dll's base the patches' addresses into it assume (the reference runs').",
        "pub const BASE: u32 = 0x%x;" % BASE,
        "",
        "/// `(address, bytes)`, in address order.",
        "pub const PATCHES: [(u32, &[u8]); %d] = [" % len(found),
    ]
    for at, data in found:
        lines.append("    (0x%x, &[%s])," % (at, ", ".join("0x%02x" % b for b in data)))
    lines.append("];")
    text = "\n".join(lines) + "\n"
    return subprocess.run(["rustfmt", "--edition", "2021", "--config-path", os.path.join(ROOT, "rust")],
                          input=text, capture_output=True, text=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("snapshot")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    snap = replay.Snapshot(args.snapshot)
    bases = [b for b, _, name, _ in snap.modules() if name.lower() == "ngp.dll"]
    if bases != [BASE]:
        sys.exit("NGP.dll is not loaded at %#x in the snapshot" % BASE)
    exe = open(os.path.join(os.environ["RBR_PATCH"], "RichardBurnsRally_SSE.exe"), "rb").read()
    text = render(patches(snap, exe))
    if args.write:
        open(OUT, "w").write(text)
        return
    if not os.path.exists(OUT) or open(OUT).read() != text:
        sys.exit("%s is out of date; run with --write" % OUT)


if __name__ == "__main__":
    main()
