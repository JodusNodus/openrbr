#!/usr/bin/env python3
"""Regenerate rust/rbr-formats/src/lsp_keys_ngp.rs from the NGP key tables in notes/ngp-load-path.md.

NGP renames stock key records and appends its own to copies of some class tables; the note lists, per class, every
record whose name is NGP's (with its member offset and the stock key it renames, if any) and the records it renames
in the stock tables it doesn't copy. A renamed stock key no longer parses under NGP.

Run from the repo root:

    python3 -I -B scripts/gen-ngp-lsp-keys.py
"""
import re

NOTE = "notes/ngp-load-path.md"
OUT = "rust/rbr-formats/src/lsp_keys_ngp.rs"
CLASSES = {
    "CCar::CDef": "CarDef",
    "CDrive::CDef": "DriveDef",
    "CDrive::CSetup": "DriveSetup",
    "CDrive::CSetupOptions": "DriveSetupOptions",
    "CEngine::CDef": "EngineDef",
    "CEngine::CSetup": "EngineSetup",
    "CEngine::CSetupOptions": "EngineSetupOptions",
    "CMaterialManager": "MaterialManager",
    "CPhysics::CDef": "PhysDef",
    "CTyre::CDef": "TyreDef",
    "CVehicleControlUnit::CDef": "VcuDef",
    "CWheel::CDef": "WheelDef",
}


def offset(cls, member):
    """A key's offset as lsp_keys stores it: the member offset, or for MaterialManager the surface id
    (w2 = 88 * id + 3)."""
    off = int(member, 16)
    if cls != "MaterialManager":
        return off
    w2 = off // 4
    assert (w2 - 3) % 88 == 0, member
    return (w2 - 3) // 88


def main():
    records, removed = [], []
    cls = None
    in_place = False
    for line in open(NOTE):
        m = re.match(r"### (\S+) \(dict", line)
        if m:
            cls = CLASSES[m.group(1)]
            continue
        if line.startswith("## Renamed in place"):
            in_place = True
            continue
        if in_place:
            m = re.match(r"\| (\S+) \| `(\w+)` \| `(\w+)` \| `\+(0x[0-9a-f]+)` \|", line)
            if m:
                c = CLASSES[m.group(1)]
                records.append((c, m.group(2), offset(c, m.group(4))))
                removed.append((c, m.group(3)))
            continue
        m = re.match(r"\| `(\w+)` \| `\+(0x[0-9a-f]+)` \| (.*) \|$", line)
        if m and cls:
            records.append((cls, m.group(1), offset(cls, m.group(2))))
            removed += [(cls, k) for k in re.findall(r"`(\w+)` \(renamed\)", m.group(3))]
    out = [
        "//! The `.lsp` keys under NGP 7.4.778 (`notes/ngp-load-path.md`): NGP renames stock key records and appends",
        "//! its own to copies of some class tables, so its `*_NGP` keys land in members of the 1.02 definitions",
        "//! through the stock parser. Generated by `scripts/gen-ngp-lsp-keys.py` from the note; do not edit.",
        "",
        "use crate::lsp_keys::{Class, KeyInfo, ReaderKind, KEYS, PARENTS};",
        "",
        "/// NGP's key records: the class, the key and its offset (as [`crate::lsp_keys::KeyInfo::offset`]: the member",
        "/// offset, or the surface id under [`Class::MaterialManager`]).",
        "pub const NGP_RECORDS: &[(Class, &str, u32)] = &[",
    ]
    out += ['    (Class::%s, "%s", %#x),' % r for r in records]
    out += [
        "];",
        "",
        "/// Stock keys NGP renames: they no longer parse under NGP.",
        "pub const NGP_REMOVED: &[(Class, &str)] = &[",
    ]
    out += ['    (Class::%s, "%s"),' % r for r in removed]
    out += [
        "];",
        "",
        "/// The key record of `key` in `class` under NGP, else in its parents (`None` when neither has it), as",
        "/// [`crate::lsp_keys::key_info`] for 1.02. An NGP record takes the reader, child and composite of the stock",
        "/// record at its offset (a renamed one keeps its member), or for a surface the material's; another appended one",
        "/// has none of them, and the parser reads its member by the member object's own type, as the original's",
        "/// `CBase::Parse` does.",
        "pub fn ngp_key_info(class: Class, key: &str) -> Option<KeyInfo> {",
        "    if let Some(&(_, key, offset)) = NGP_RECORDS.iter().find(|(c, k, _)| *c == class && *k == key) {",
        "        // A renamed record keeps its member's; a surface NGP appends is a material like every other.",
        "        let stock = KEYS.iter().find(|i| i.class == class && (i.offset == offset || class == Class::MaterialManager));",
        "        let stock = stock.map(|info| KeyInfo { offset, ..*info });",
        "        return Some(match stock {",
        "            Some(info) => KeyInfo { key, used_in_retail: false, ..info },",
        "            None => KeyInfo {",
        "                class,",
        "                key,",
        "                offset,",
        "                reader: ReaderKind::Unknown,",
        "                child: None,",
        "                composite: None,",
        "                used_in_retail: false,",
        "            },",
        "        });",
        "    }",
        "    (!NGP_REMOVED.contains(&(class, key)))",
        "        .then(|| KEYS.iter().find(|i| i.class == class && i.key == key).copied())",
        "        .flatten()",
        "        .or_else(|| {",
        "            PARENTS.iter().filter(|(child, _)| *child == class).find_map(|(_, parent)| ngp_key_info(*parent, key))",
        "        })",
        "}",
        "",
        "/// The offset of `key` in `class` under NGP, else in its parents (`None` when neither has it), as",
        "/// [`crate::lsp_keys::key_offset`] for 1.02.",
        "pub fn ngp_key_offset(class: Class, key: &str) -> Option<u32> {",
        "    ngp_key_info(class, key).map(|info| info.offset)",
        "}",
    ]
    open(OUT, "w").write("\n".join(out) + "\n")
    print("%d records, %d renamed stock keys" % (len(records), len(removed)))


if __name__ == "__main__":
    main()
