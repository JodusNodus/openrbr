#!/usr/bin/env python3
"""Regenerate crates/rbr-physics/src/ngp/stage_materials.rs: what NGP 7.4.778's stage init (`0x1004e360`, run by NGP's
state listener `0x100f06b0` as the race starts) writes into the physics definition (`CPhysics::CDef`): the gravity
and `MaxTimeStep` (1/720 s), and its material table, through 288 setters (`0x100b86b0`) whose arguments are
constants. The table depends only on the definition's `+0x1607c` (0x30a, or anything else).

The function runs in unicorn on NGP.dll's sections, on a zeroed definition with `+0x1607c` set, with NGP's game lookup
(`0x1002a690`) returning a zeroed block (its `+0x10`, 0, is not the replay mode 1, so `MaxTimeStep` is 1/720). The
output is the definition's written words per case, as runs of words 0x10 apart (the members' values).

Run from the repo root with the harness venv (unicorn):

    RBR_NGP=original/ngp .venv/bin/python -I -B scripts/gen-ngp-stage-materials.py [--write]

Without `--write` the script checks that its output matches the checked-in file byte for byte and exits nonzero when
it does not. The output goes through `rustfmt`.
"""

import argparse
import os
import struct
import subprocess
import sys

from unicorn import Uc, UC_ARCH_X86, UC_MODE_32, UC_PROT_ALL, UC_HOOK_MEM_WRITE, UC_HOOK_CODE
from unicorn.x86_const import UC_X86_REG_ECX, UC_X86_REG_ESP, UC_X86_REG_EAX, UC_X86_REG_EIP

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "crates", "rbr-physics", "src", "ngp", "stage_materials.rs")

FILE_BASE = 0x10000000
STAGE_INIT, GAME_LOOKUP = 0x1004E360, 0x1002A690
DEF, DEF_SIZE = 0x20000000, 0x20000
GAME, GAME_SIZE = 0x21000000, 0x190000
STACK, STACK_SIZE = 0x30000000, 0x10000
RETURN = 0x40000000
KIND = 0x1607C
STRIDE = 0x10


def sections(dll):
    pe, = struct.unpack_from("<I", dll, 0x3C)
    count, = struct.unpack_from("<H", dll, pe + 6)
    optional, = struct.unpack_from("<H", dll, pe + 20)
    for i in range(count):
        vsize, va, rsize, raw = struct.unpack_from("<IIII", dll, pe + 24 + optional + 40 * i + 8)
        yield FILE_BASE + va, max(vsize, rsize), dll[raw:raw + rsize]


def run(dll, kind):
    """The definition's written words `{offset: word}` with `+0x1607c` = `kind`."""
    mu = Uc(UC_ARCH_X86, UC_MODE_32)
    for va, size, data in sections(dll):
        mu.mem_map(va & ~0xFFF, ((va + size + 0xFFF) & ~0xFFF) - (va & ~0xFFF), UC_PROT_ALL)
        mu.mem_write(va, data)
    for base, size in [(DEF, DEF_SIZE), (GAME, GAME_SIZE), (STACK, STACK_SIZE), (RETURN, 0x1000)]:
        mu.mem_map(base, size, UC_PROT_ALL)
    mu.mem_write(RETURN, b"\xf4")
    mu.mem_write(DEF + KIND, struct.pack("<I", kind))
    written = set()

    def on_write(_mu, _access, addr, size, _value, _data):
        if DEF <= addr < DEF + DEF_SIZE:
            assert size == 4 and addr % 4 == 0, hex(addr)
            written.add(addr - DEF)
        elif GAME <= addr < GAME + GAME_SIZE:
            pass
        elif not STACK <= addr < STACK + STACK_SIZE:
            raise SystemExit("a write at %#x" % addr)

    def on_code(mu, addr, _size, _data):
        if addr == GAME_LOOKUP:  # return the game block (cdecl, no arguments)
            esp = mu.reg_read(UC_X86_REG_ESP)
            mu.reg_write(UC_X86_REG_EAX, GAME)
            mu.reg_write(UC_X86_REG_EIP, struct.unpack("<I", mu.mem_read(esp, 4))[0])
            mu.reg_write(UC_X86_REG_ESP, esp + 4)

    mu.hook_add(UC_HOOK_MEM_WRITE, on_write)
    mu.hook_add(UC_HOOK_CODE, on_code, begin=GAME_LOOKUP, end=GAME_LOOKUP)
    esp = STACK + STACK_SIZE // 2
    mu.mem_write(esp, struct.pack("<I", RETURN))
    mu.reg_write(UC_X86_REG_ESP, esp)
    mu.reg_write(UC_X86_REG_ECX, DEF)
    mu.emu_start(STAGE_INIT, RETURN)
    out = bytes(mu.mem_read(DEF, DEF_SIZE))
    return {o: struct.unpack_from("<I", out, o)[0] for o in sorted(written)}


def runs(words):
    """`(offset, words)` runs of words 0x10 apart (the members' values)."""
    out = []
    for o, w in words.items():
        if out and out[-1][0] + STRIDE * len(out[-1][1]) == o:
            out[-1][1].append(w)
        else:
            out.append((o, [w]))
    return out


def table(name, doc, words):
    found = runs(words)
    lines = ["/// %s" % doc, "pub const %s: [(u32, &[u32]); %d] = [" % (name, len(found))]
    for o, ws in found:
        lines.append("    (0x%x, &[%s])," % (o, ", ".join("0x%08x" % w for w in ws)))
    lines.append("];")
    return lines


def render(dll):
    lines = [
        "//! What NGP 7.4.778's stage init (`0x1004e360`) writes into the physics definition (generated by",
        "//! `scripts/gen-ngp-stage-materials.py`; do not edit): the gravity, `MaxTimeStep` (1/720 s) and the material",
        "//! table, by the definition's `+0x1607c` ([`KIND`]).",
        "",
        "/// The definition's word that picks the table.",
        "pub const KIND: u32 = 0x%x;" % KIND,
        "",
    ]
    lines += table("WORDS_30A", "The words with `+0x1607c` 0x30a, as `(offset, words)` runs, the words 0x10 apart.",
                   run(dll, 0x30A))
    lines.append("")
    lines += table("WORDS_OTHER", "The words with any other `+0x1607c`.", run(dll, 0))
    text = "\n".join(lines) + "\n"
    return subprocess.run(["rustfmt", "--edition", "2021", "--config-path", ROOT],
                          input=text, capture_output=True, text=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    ngp = os.environ.get("RBR_NGP", os.path.join(ROOT, "original", "ngp"))
    dll = open(os.path.join(ngp, "7.4.778", "Plugins", "NGP.dll"), "rb").read()
    text = render(dll)
    if args.write:
        open(OUT, "w").write(text)
        return
    if not os.path.exists(OUT) or open(OUT).read() != text:
        sys.exit("%s is out of date; run with --write" % OUT)


if __name__ == "__main__":
    main()
