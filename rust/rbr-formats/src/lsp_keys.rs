/// Value reader for one key: the member `Parse` the loader
/// dispatches to (`CBase::Parse` looks the member up by key and calls
/// its virtual `Parse`). `Unknown` means no retail `.lsp` attributes
/// the key to its class, so no member construction confirms it.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
pub enum ReaderKind {
    Real,
    Unsigned,
    Integer,
    Bitfield,
    Vector,
    Child,
    ObjIdQueue,
    Unknown,
}

/// Composite member holding a key's value: the key addresses one
/// sub-word (see the `kind` column of the notes file). `None` for
/// direct members.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
pub enum CompositeKind {
    RealTriple,
    Real10,
    Mixed50,
    UnsignedPair,
    UnsignedTriple,
    RealPair,
    Real2A,
    Real2B,
    Block60,
    E39CDefCtorA,
    E39Hook5140,
}

/// One key-table record: the owning class, the key, and `w2 * 4`.
/// For [`Class::MaterialManager`] the offset is the surface id
