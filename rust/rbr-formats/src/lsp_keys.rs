/// The record of `key` in `class`, else in its parents (`None` when the key
/// is unknown to the class and its parents). Mirrors `CBase::Parse` key
/// dispatch.
pub fn key_info(class: Class, key: &str) -> Option<&'static KeyInfo> {
    KEYS.iter()
        .find(|info| info.class == class && info.key == key)
        .or_else(|| PARENTS.iter().filter(|(child, _)| *child == class).find_map(|(_, parent)| key_info(*parent, key)))
}

/// Byte offset of `key` in `class` (`None` when the key is unknown to the
/// class and its parents).
pub fn key_offset(class: Class, key: &str) -> Option<u32> {
    key_info(class, key).map(|info| info.offset)
}

